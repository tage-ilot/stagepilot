/** The color of a section by its exact name; grey when the table does not know it. */
export function sectionColor(name: string): string {
  return Object.hasOwn(SECTION_COLORS, name) ? SECTION_COLORS[name]! : UNKNOWN_SECTION_COLOR;
}
